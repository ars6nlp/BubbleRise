using UnityEngine;

namespace BubbleRise
{
    /// <summary>
    /// Общий размер пузырька и стража — одним числом на всю игру.
    ///
    /// **Почему одно число, а не правка двух радиусов.** От размера шарика
    /// считается не только он сам: расстояние, на котором страж держится от
    /// пузырька, отступ препятствий от края, требуемая ширина прохода, величина
    /// частиц удара. Правка «в двух местах» каждый раз оставляла бы половину
    /// этого списка в прежнем масштабе, и заметить расхождение можно было бы
    /// только по ощущению, что что-то не сходится.
    ///
    /// **Почему статический класс.** Ровно та же причина, что у
    /// <see cref="Difficulty"/> и <see cref="Visuals"/>: число нужно контроллерам,
    /// спавнеру, эффектам и проверке столкновений, и протягивать его через
    /// полдюжины Init значило бы тащить конфиг туда, где он больше ничего не
    /// делает.
    ///
    /// **Чего он НЕ касается.** Интерфейса: монета, значки, кнопки и шрифты
    /// живут в единицах холста и к миру отношения не имеют. И хитбоксов
    /// препятствий: их размер — вопрос баланса, а не внешнего вида игрока.
    /// </summary>
    public static class PlayerSize
    {
        /// <summary>Множитель размера. 1 — как было, 0.8 — на пятую часть меньше.</summary>
        public static float Scale { get; private set; } = 1f;

        public static void Bind(GameConfig cfg)
        {
            Scale = cfg != null ? Mathf.Clamp(cfg.playerScaleMultiplier, 0.5f, 1.5f) : 1f;
        }

        /// <summary>Радиус пузырька с учётом множителя.</summary>
        public static float Bubble(GameConfig cfg) => cfg.bubbleRadius * Scale;

        /// <summary>Радиус стража с учётом множителя.</summary>
        public static float Guardian(GameConfig cfg) => cfg.guardianRadius * Scale;
    }
}
